// Aetherium Backport for Minecraft 1.8.9 (Forge 11.15.1.2318). Built with Essential's
// architectury-loom (RetroFuturaGradle only covers 1.7.10 / 1.12.2). There is no MixinBooter on
// 1.8.9, so Mixin 0.7.11 is bundled in the jar and started through its tweaker.
import org.apache.commons.lang3.SystemUtils

plugins {
    idea
    java
    id("gg.essential.loom") version "0.10.0.+"
    id("dev.architectury.architectury-pack200") version "0.1.3"
    id("com.github.johnrengelman.shadow") version "8.1.1"
}

val baseGroup: String by project
val mcVersion: String by project
val modVersion: String by project
val modid: String by project
val modName: String by project
val modDescription: String by project

version = modVersion
group = baseGroup

java {
    toolchain.languageVersion.set(JavaLanguageVersion.of(8))
}

loom {
    log4jConfigs.from(file("log4j2.xml"))
    launchConfigs {
        "client" {
            property("mixin.debug.verbose", "false")
            arg("--tweakClass", "org.spongepowered.asm.launch.MixinTweaker")
        }
    }
    runConfigs {
        "client" {
            if (SystemUtils.IS_OS_MAC_OSX) {
                vmArgs.remove("-XstartOnFirstThread")
            }
        }
        remove(getByName("server"))
    }
    forge {
        pack200Provider.set(dev.architectury.pack200.java.Pack200Adapter())
        mixinConfig("mixins.$modid.json")
    }
    mixin {
        defaultRefmapName.set("mixins.$modid.refmap.json")
    }
}

// ---------------------------------------------------------------------------------------------
// The Minecraft-free part of the main mod (config, the settings screen view, frame statistics,
// frame pacing, zoom, fog culling, the terrain culling planner, ...) is compiled from ../common
// unchanged, so all versions share one source of truth. The list is explicit: shared-sources.txt
// (generated by ci/shared_closure.py). Everything that touches Minecraft is written for 1.8.9 in src/.
val sharedSources = file("shared-sources.txt").readLines()
    .map { it.trim() }
    .filter { it.isNotEmpty() && !it.startsWith("#") }
    .map { "com/aetherium/$it" }
val syncShared = tasks.register<Sync>("syncSharedSources") {
    from("../common/src/main/java") {
        include(if (sharedSources.isEmpty()) listOf("__none__") else sharedSources)
    }
    into(layout.buildDirectory.dir("shared-src"))
}
sourceSets.main {
    java.srcDir(syncShared)
    output.setResourcesDir(sourceSets.main.flatMap { it.java.classesDirectory })
}

repositories {
    mavenCentral()
    maven("https://repo.spongepowered.org/maven/")
}

val shadowImpl: Configuration by configurations.creating {
    configurations.implementation.get().extendsFrom(this)
}

dependencies {
    minecraft("com.mojang:minecraft:1.8.9")
    mappings("de.oceanlabs.mcp:mcp_stable:22-1.8.9")
    forge("net.minecraftforge:forge:1.8.9-11.15.1.2318-1.8.9")

    shadowImpl("org.spongepowered:mixin:0.7.11-SNAPSHOT") {
        isTransitive = false
    }
    annotationProcessor("org.spongepowered:mixin:0.8.5-SNAPSHOT")
}

tasks.withType(JavaCompile::class) {
    options.encoding = "UTF-8"
}

tasks.withType(org.gradle.jvm.tasks.Jar::class) {
    archiveBaseName.set("aetherium-backport")
    manifest.attributes.run {
        this["FMLCorePluginContainsFMLMod"] = "true"
        this["ForceLoadAsMod"] = "true"
        this["TweakClass"] = "org.spongepowered.asm.launch.MixinTweaker"
        this["TweakOrder"] = "0"
        this["MixinConfigs"] = "mixins.$modid.json"
        this["Implementation-Title"] = modName
        this["Implementation-Version"] = modVersion
        this["Implementation-Vendor"] = "Team_Aerix"
    }
}

// CI smoke runs check every injector: each must hit at least once (mixin.debug.countInjections),
// and the config is made non-required there so every failure is logged in one run, not just the first.
val smokeDir: String? = System.getenv("AETHERIUM_SMOKE")?.takeIf { it.isNotEmpty() }

tasks.processResources {
    inputs.property("smoke", smokeDir != null)
    if (smokeDir != null) {
        filesMatching("mixins.$modid.json") {
            filter { line -> line.replace("\"required\": true", "\"required\": false") }
        }
    }
    inputs.property("version", modVersion)
    inputs.property("mcversion", mcVersion)
    inputs.property("modid", modid)
    inputs.property("name", modName)
    inputs.property("description", modDescription)
    filesMatching(listOf("mcmod.info", "pack.mcmeta")) {
        expand(inputs.properties)
    }
    from("../common/src/main/resources/assets/aetherium/icon.png") {
        into("assets/aetherium")
    }
}

val remapJar by tasks.named<net.fabricmc.loom.task.RemapJarTask>("remapJar") {
    archiveClassifier.set("")
    from(tasks.shadowJar)
    input.set(tasks.shadowJar.get().archiveFile)
}

tasks.jar {
    archiveClassifier.set("without-deps")
    destinationDirectory.set(layout.buildDirectory.dir("intermediates"))
}

tasks.shadowJar {
    destinationDirectory.set(layout.buildDirectory.dir("intermediates"))
    archiveClassifier.set("non-obfuscated-with-deps")
    configurations = listOf(shadowImpl)
    // Mixin's own service files and signatures are not needed by the 1.8.9 launch wrapper.
    exclude("META-INF/*.SF", "META-INF/*.DSA", "META-INF/*.RSA", "LICENSE.txt")
}

tasks.assemble.get().dependsOn(tasks.remapJar)

// CI smoke test (AETHERIUM_SMOKE=<dir> ./gradlew runClient). Inert otherwise.
tasks.matching { it.name == "runClient" }.configureEach {
    val task = this as JavaExec
    if (smokeDir != null) {
        task.jvmArgs("-Daetherium.smoke=$smokeDir", "-Dmixin.debug.countInjections=true")
        task.args("--width", "1280", "--height", "720")
    }
}
