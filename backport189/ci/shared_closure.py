#!/usr/bin/env python3
"""Lists the common/ sources the 1.8.9 backport needs: the transitive closure of every com.aetherium
class referenced from backport189/src, minus the classes the backport provides itself.
Writes backport189/shared-sources.txt; fails if a shared class touches net.minecraft."""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
COMMON = os.path.join(ROOT, 'common/src/main/java')
BACK = os.path.join(ROOT, 'backport189/src/main/java')

def index(base):
    out = {}
    for d, _, fs in os.walk(base):
        for f in fs:
            if f.endswith('.java'):
                p = os.path.join(d, f)
                out[os.path.relpath(p, base)[:-5].replace(os.sep, '.')] = p
    return out

common, back = index(COMMON), index(BACK)
by_pkg = {}
for fq in common:
    by_pkg.setdefault(fq.rsplit('.', 1)[0], set()).add(fq.rsplit('.', 1)[1])

def refs(path, fq):
    src = open(path, encoding='utf-8').read()
    src = re.sub(r'//[^\n]*|/\*.*?\*/', '', src, flags=re.S)
    pkg = fq.rsplit('.', 1)[0]
    found = set(re.findall(r'\b(com\.aetherium(?:\.[a-z][a-z0-9_]*)*\.[A-Z]\w*)', src))
    words = set(re.findall(r'\b([A-Z]\w*)\b', src))
    for name in by_pkg.get(pkg, ()):
        if name in words:
            found.add(pkg + '.' + name)
    return found

needed, todo = set(), []
for fq, p in back.items():
    todo.extend(refs(p, fq))
while todo:
    fq = todo.pop()
    while fq not in common and fq not in back and fq.count('.') > 2:
        fq = fq.rsplit('.', 1)[0]
    if fq in back or fq in needed or fq not in common:
        continue
    needed.add(fq)
    todo.extend(refs(common[fq], fq))

bad, lines = [], []
for fq in sorted(needed):
    src = open(common[fq], encoding='utf-8').read()
    if re.search(r'^import net\.minecraft|^import com\.mojang', src, re.M):
        bad.append(fq)
    lines.append(fq.replace('.', '/')[len('com/aetherium/'):] + '.java')
with open(os.path.join(ROOT, 'backport189/shared-sources.txt'), 'w') as f:
    f.write('# Minecraft-free sources of the main mod (common/src/main/java/com/aetherium/...), compiled\n'
            '# unchanged into the 1.8.9 backport. Generated by backport189/ci/shared_closure.py.\n')
    f.write('\n'.join(lines) + '\n')
print(len(lines), 'shared classes')
if bad:
    sys.exit('shared classes touching Minecraft: ' + ', '.join(bad))
